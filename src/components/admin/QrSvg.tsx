"use client";

import { useEffect, useState } from "react";
import QRCode from "qrcode";

/** Inline SVG QR code (black on white), sized by its container. */
export function QrSvg({ value, className }: { value: string; className?: string }) {
  const [svg, setSvg] = useState("");
  useEffect(() => {
    let live = true;
    QRCode.toString(value, { type: "svg", margin: 0, errorCorrectionLevel: "M", color: { dark: "#000000", light: "#FFFFFF" } })
      .then((s) => live && setSvg(s))
      .catch(() => live && setSvg(""));
    return () => {
      live = false;
    };
  }, [value]);
  // Generated by the qrcode library from our own URL — not user HTML.
  return <span className={className} role="img" aria-label="QR code" dangerouslySetInnerHTML={{ __html: svg }} />;
}
