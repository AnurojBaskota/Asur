-- Supabase exposes the public schema through its REST/GraphQL API using the
-- anon key. Enable Row Level Security with NO policies so those APIs can read
-- or write nothing. The app connects as the database owner via Prisma, which
-- bypasses RLS, so the store keeps working.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['Category','Product','ProductImage','Variant','StockMovement','Customer','Order','OrderItem','OrderEvent','Setting','Page','_prisma_migrations']
  LOOP
    IF to_regclass(format('public.%I', t)) IS NOT NULL THEN
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    END IF;
  END LOOP;
END $$;
